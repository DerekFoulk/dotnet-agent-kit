    Context 'Building and checking the page' {
        BeforeAll {
            $script:open = '<!-- sources from docs/standards: generated by Build-AuthoritiesPage.ps1 from docs/authorities.yml; edit those, not this block (ADR-0073) -->'
            $script:close = '<!-- end sources -->'
            $script:quotesOpen = '<!-- quotes from docs/standards: generated by Build-AuthoritiesPage.ps1 from docs/authorities.yml; edit those, not this block (ADR-0094) -->'
            $script:quotesClose = '<!-- end quotes -->'
            $script:defaultData = @(
                'sources:', '  - name: IETF', '    publisher: IETF', '    class: authority', '    covers: RFCs', '    match:', '      - https://www.rfc-editor.org/'
                'licenses:', '  - id: CC-BY-4.0', '    name: CC BY 4.0', '    url: https://creativecommons.org/licenses/by/4.0/'
                'works:', '  - title: RFC 9457', '    author: M. Nottingham, E. Wilde and S. Dalal', '    source: https://www.rfc-editor.org/rfc/rfc9457'
                '    license: CC-BY-4.0', '    stated: https://www.rfc-editor.org/copyright/', '    checked: 2026-11-25', '    match:', '      - https://www.rfc-editor.org/'
            ) -join "`n"

            function New-Repo {
                # [object], so $null means "no file": a [string] parameter would turn it into ''.
                param([string] $Page, [object] $Data = $script:defaultData, [object] $Notices = "# Notices`n`n$quotesOpen`nold`n$quotesClose`n")
                $root = Join-Path $TestDrive "repo-$(New-Guid)"
                $script:standards = Join-Path $root 'docs' 'standards'
                New-Item -ItemType Directory -Path $script:standards | Out-Null
                $quoted = 'https://www.rfc-editor.org/rfc/rfc9457'
                New-StandardsFile -Topic 'api-design' -Rules @(New-Rule -Id 'API-002' -Sources "$quoted, retrieved 2026-11-01" -Quotes $quoted, $quoted)
                if ($null -ne $Data) { Set-Content -Path (Join-Path $root 'docs' 'authorities.yml') -Value $Data -NoNewline }
                Set-Content -Path (Join-Path $root 'docs' 'authorities.md') -Value $Page -NoNewline
                if ($null -ne $Notices) { Set-Content -Path (Join-Path $root 'THIRD-PARTY-NOTICES.md') -Value $Notices -NoNewline }
                $root
            }

            function Read-Page([string] $Root) { (Get-Content -Raw -Path (Join-Path $Root 'docs' 'authorities.md')) -replace "`r`n", "`n" }
            function Read-Notices([string] $Root) { (Get-Content -Raw -Path (Join-Path $Root 'THIRD-PARTY-NOTICES.md')) -replace "`r`n", "`n" }
        }

        It 'fills the quotes block of THIRD-PARTY-NOTICES.md with each quoted work: title, author, license, where it''s stated, its quotes and the standards quoting it' {
            $notices = "# Notices`n`nBy hand.`n`n$quotesOpen`nold`n$quotesClose`n`nMIT text.`n"
            $root = New-Repo -Page "$open`nold`n$close`n" -Notices $notices

            Invoke-AuthoritiesPageBuild -RepoRoot $root 6>$null | Should -Be 0

            $text = Read-Notices $root
            $text | Should -Match "(?s)^# Notices`n`nBy hand\.`n`n$([regex]::Escape($quotesOpen))`nThe rules quote 2 passages from 1 works\.`n.*`n$([regex]::Escape($quotesClose))`n`nMIT text\.`n$"
            $text | Should -Match ([regex]::Escape('| [RFC 9457](https://www.rfc-editor.org/rfc/rfc9457) | M. Nottingham, E. Wilde and S. Dalal | [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) | <https://www.rfc-editor.org/copyright/>, checked 2026-11-25 | 2 | [api-design.md](docs/standards/api-design.md) |'))
            Invoke-AuthoritiesPageBuild -RepoRoot $root -Check 6>$null | Should -Be 0
        }

        It 'with -Check, fails on a stale quotes block in THIRD-PARTY-NOTICES.md and writes nothing' {
            $root = New-Repo -Page "$open`nold`n$close`n"
            Invoke-AuthoritiesPageBuild -RepoRoot $root 6>$null | Should -Be 0
            $stale = "# Notices`n`n$quotesOpen`nold`n$quotesClose`n"
            Set-Content -Path (Join-Path $root 'THIRD-PARTY-NOTICES.md') -Value $stale -NoNewline

            $output = @(Invoke-AuthoritiesPageBuild -RepoRoot $root -Check 6>&1)

            @($output | Where-Object { $_ -is [int] }) | Should -Be @(1)
            ($output | Where-Object { $_ -is [System.Management.Automation.InformationRecord] }) -join "`n" | Should -Match 'out of date: THIRD-PARTY-NOTICES\.md'
            Read-Notices $root | Should -BeExactly $stale
        }

        It 'fails, says why, and writes neither file when THIRD-PARTY-NOTICES.md <Case>' -ForEach @(
            @{ Case = 'is missing'; Notices = $null; Reason = 'THIRD-PARTY-NOTICES\.md is missing' }
            @{ Case = 'has no quotes block'; Notices = "# Notices`n`nNo markers.`n"; Reason = "THIRD-PARTY-NOTICES\.md needs one block: one '<!-- quotes from docs/standards" }
        ) {
            $page = "$open`nold`n$close`n"
            $root = New-Repo -Page $page -Notices $Notices

            $output = @(Invoke-AuthoritiesPageBuild -RepoRoot $root 6>&1)

            @($output | Where-Object { $_ -is [int] }) | Should -Be @(1)
            ($output | Where-Object { $_ -is [System.Management.Automation.InformationRecord] }) -join "`n" | Should -Match $Reason
            Read-Page $root | Should -BeExactly $page
        }

        It 'fills only the block, leaving the text around it, and a check then passes' {
            $root = New-Repo -Page "# Sources`n`nBy hand.`n`n$open`nold`n$close`n`nAlso by hand.`n"

            Invoke-AuthoritiesPageBuild -RepoRoot $root 6>$null | Should -Be 0

            $page = Read-Page $root
            $page | Should -Match "(?s)^# Sources`n`nBy hand\.`n`n$([regex]::Escape($open))`nThe rules cite 1 pages.*<https://www\.rfc-editor\.org/rfc/rfc9457> \| \[API-002\]\(standards/api-design\.md\) \|`n$([regex]::Escape($close))`n`nAlso by hand\.`n$"
            Invoke-AuthoritiesPageBuild -RepoRoot $root -Check 6>$null | Should -Be 0
        }

        It 'with -Check, fails on a stale block and writes nothing' {
            $page = "# Sources`n`n$open`nold`n$close`n"
            $root = New-Repo -Page $page

            $output = @(Invoke-AuthoritiesPageBuild -RepoRoot $root -Check 6>&1)

            @($output | Where-Object { $_ -is [int] }) | Should -Be @(1)
            $text = ($output | Where-Object { $_ -is [System.Management.Automation.InformationRecord] }) -join "`n"
            $text | Should -Match 'out of date: docs/authorities\.md'
            # The first line that differs, so a failure in CI shows what changed without a local run.
            $text | Should -Match "first difference, line 4:`n\s+expected: The rules cite 1 pages[^`n]*`n\s+found:\s+old"
            Read-Page $root | Should -BeExactly $page
        }

        It 'passes a current page that a Windows checkout gave CRLF line endings' {
            $root = New-Repo -Page "# Sources`n`n$open`nold`n$close`n"
            Invoke-AuthoritiesPageBuild -RepoRoot $root 6>$null | Should -Be 0
            $path = Join-Path $root 'docs' 'authorities.md'
            Set-Content -Path $path -Value ((Get-Content -Raw -Path $path) -replace "`r?`n", "`r`n") -NoNewline

            Invoke-AuthoritiesPageBuild -RepoRoot $root -Check 6>$null | Should -Be 0
        }

        It 'fails, says why, and writes nothing when <Case>' -ForEach @(
            @{ Case = 'the page has no block'; Page = "# Sources`n`nNo markers.`n"; Data = 'default'; Reason = 'needs one block' }
            @{ Case = 'the block has no end marker'; Page = "# Sources`n`n<!-- sources from docs/standards: x -->`nold`n"; Data = 'default'; Reason = 'needs one block' }
            @{ Case = 'an opening marker is quoted on a line of its own before the block'; Data = 'default'; Reason = 'needs one block'
                Page = "# Sources`n`n``````text`n<!-- sources from docs/standards: an example -->`n```````n`nHand-written prose.`n`n$open`nold`n$close`n" }
            @{ Case = 'docs/authorities.yml is missing'; Page = "$open`nold`n$close`n"; Data = $null; Reason = 'authorities\.yml is missing' }
            @{ Case = 'docs/authorities.yml has no sources list'; Page = "$open`nold`n$close`n"; Data = "entries: []`n"; Reason = "has no 'sources' list" }
            @{ Case = 'a cited URL has no entry'; Page = "$open`nold`n$close`n"; Reason = 'matches no entry'
                Data = "sources:`n  - name: Other`n    publisher: Other`n    class: authority`n    covers: x`n    match:`n      - https://example.com/`n" }
        ) {
            $root = if ($Data -eq 'default') { New-Repo -Page $Page } else { New-Repo -Page $Page -Data $Data }

            $output = @(Invoke-AuthoritiesPageBuild -RepoRoot $root 6>&1)

            @($output | Where-Object { $_ -is [int] }) | Should -Be @(1)
            ($output | Where-Object { $_ -is [System.Management.Automation.InformationRecord] }) -join "`n" | Should -Match $Reason
            Read-Page $root | Should -BeExactly $Page
        }
    }

    Context 'The notices block' {
        BeforeAll {
            $licenses = @(
                [ordered]@{ id = 'CC-BY-4.0'; name = 'CC BY 4.0'; url = 'https://creativecommons.org/licenses/by/4.0/'; note = 'Credit the author.' }
                [ordered]@{ id = 'W3C'; name = 'W3C Document License'; url = 'https://www.w3.org/copyright/document-license-2023/' }
                [ordered]@{ id = 'MIT'; name = 'MIT'; url = 'https://opensource.org/license/mit'; note = 'Unused, so left out.' }
            )
            $works = @(
                [ordered]@{ title = 'WCAG 2.2'; author = 'W3C'; source = 'https://www.w3.org/TR/WCAG22/'; license = 'W3C'; stated = 'https://www.w3.org/TR/WCAG22/'
                    checked = '2026-11-25'; match = @('https://www.w3.org/TR/WCAG22/'); notice = 'Copyright © 2020-2024 World Wide Web Consortium. W3C Recommendation 12 December 2024.' }
                [ordered]@{ title = 'ASP.NET Core docs'; author = 'Microsoft and contributors'; copyright = 'Copyright (c) Microsoft Corporation'
                    source = 'https://learn.microsoft.com/aspnet/core/'; license = 'CC-BY-4.0'; stated = 'https://github.com/dotnet/AspNetCore.Docs/blob/main/LICENSE'
                    checked = '2026-11-25'; match = @('https://learn.microsoft.com/aspnet/') }
            )
            $quoted = @(
                [pscustomobject]@{ Url = 'https://learn.microsoft.com/aspnet/core/a'; RuleId = 'API-001'; File = 'api-design.md' }
                [pscustomobject]@{ Url = 'https://learn.microsoft.com/aspnet/core/b'; RuleId = 'ASP-001'; File = 'aspnetcore.md' }
                [pscustomobject]@{ Url = 'https://learn.microsoft.com/aspnet/core/a'; RuleId = 'API-002'; File = 'api-design.md' }
                [pscustomobject]@{ Url = 'https://www.w3.org/TR/WCAG22/'; RuleId = 'UI-001'; File = 'ui.md' }
            )
            $block = ConvertTo-NoticesBlock -Quoted $quoted -Works $works -Licenses $licenses
        }

        It 'lists the works by title, with a copyright beside the author, and each standard quoting a work once, sorted' {
