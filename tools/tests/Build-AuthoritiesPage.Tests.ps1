        }

        It 'reports a license with no <Field>, and a license no work uses' -ForEach @(@{ Field = 'id' }, @{ Field = 'name' }, @{ Field = 'url' }) {
            $license = New-License
            $license.Remove($Field)
            $id = if ($Field -eq 'id') { '(no id)' } else { 'CC-BY-4.0' }

            $lines = (Get-CheckOutput -Works @(New-Work) -Licenses @($license, (New-License -Id 'MIT'))).Lines

            $lines | Should -Contain "license '$id' is missing '$Field'"
            $lines | Should -Contain "license 'MIT' is used by no work; remove it"
        }
    }

