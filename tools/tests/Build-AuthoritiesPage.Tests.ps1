    Context 'Problems with the quoted works and their licenses' {
        BeforeAll {
            $script:quotesOpen = '<!-- quotes from docs/standards: generated by Build-AuthoritiesPage.ps1 from docs/authorities.yml; edit those, not this block (ADR-0094) -->'

            function New-Work {
                [ordered]@{
                    title = 'RFC 9457'; author = 'M. Nottingham'; source = 'https://www.rfc-editor.org/rfc/rfc9457'; license = 'CC-BY-4.0'
                    stated = 'https://www.rfc-editor.org/copyright/'; checked = '2026-11-25'; match = @('https://www.rfc-editor.org/')
                }
            }

            function New-License([string] $Id = 'CC-BY-4.0') { [ordered]@{ id = $Id; name = "$Id name"; url = "https://example.com/$Id/" } }

            # Builds a repo whose one rule quotes RFC 9457 twice, with these works and licenses, and returns what a
            # check prints.
            function Get-CheckOutput([object[]] $Works, [object[]] $Licenses) {
                $root = Join-Path $TestDrive "repo-$(New-Guid)"
                $script:standards = Join-Path $root 'docs' 'standards'
                New-Item -ItemType Directory -Path $script:standards | Out-Null
                $quoted = 'https://www.rfc-editor.org/rfc/rfc9457'
                New-StandardsFile -Topic 'api-design' -Rules @(New-Rule -Id 'API-002' -Sources "$quoted, retrieved 2026-11-01" -Quotes $quoted)
                $data = [ordered]@{ sources = @(New-Entry -Name 'IETF' -Match 'https://www.rfc-editor.org/'); licenses = $Licenses; works = $Works }
                Set-Content -Path (Join-Path $root 'docs' 'authorities.yml') -Value (ConvertTo-Yaml $data)
                Set-Content -Path (Join-Path $root 'docs' 'authorities.md') -Value "<!-- sources from docs/standards: x -->`nold`n<!-- end sources -->`n"
                Set-Content -Path (Join-Path $root 'THIRD-PARTY-NOTICES.md') -Value "$quotesOpen`nold`n<!-- end quotes -->`n"
                $output = @(Invoke-AuthoritiesPageBuild -RepoRoot $root -Check 6>&1)
                [pscustomobject]@{
                    ExitCode = @($output | Where-Object { $_ -is [int] })
                    Lines    = @($output | Where-Object { $_ -is [System.Management.Automation.InformationRecord] } | ForEach-Object { "$_".Trim() })
                }
            }
        }

        It 'reports a quote whose page no work matches, and a work no quote matches' {
            $work = New-Work
            $work['match'] = @('https://other.example.com/')

            $result = Get-CheckOutput -Works @($work) -Licenses @(New-License)

            $result.ExitCode | Should -Be @(1)
            $result.Lines | Should -Contain 'quote from https://www.rfc-editor.org/rfc/rfc9457 (API-002) matches no work in docs/authorities.yml; add the work and its license (ADR-0094)'
            $result.Lines | Should -Contain "work 'RFC 9457' matches no quoted page; remove it"
        }

        It 'reports a work with no <Field>' -ForEach @(
            @{ Field = 'title' }, @{ Field = 'author' }, @{ Field = 'source' }, @{ Field = 'license' }, @{ Field = 'stated' }, @{ Field = 'checked' }, @{ Field = 'match' }
        ) {
            $work = New-Work
            $work.Remove($Field)
            $name = if ($Field -eq 'title') { '(no title)' } else { 'RFC 9457' }

            (Get-CheckOutput -Works @($work) -Licenses @(New-License)).Lines | Should -Contain "work '$name' is missing '$Field'"
        }

        It 'reports a work with <Case>' -ForEach @(
            @{ Case = 'a license the licenses list doesn''t have'; Field = 'license'; Value = 'MIT'
                Message = "work 'RFC 9457' license 'MIT' isn't in docs/authorities.yml's licenses" }
            @{ Case = 'a checked date that isn''t yyyy-MM-dd'; Field = 'checked'; Value = 'last week'
                Message = "work 'RFC 9457' checked 'last week' must be a date, yyyy-MM-dd" }
            @{ Case = 'a source that isn''t a URL'; Field = 'source'; Value = 'RFC 9457'
                Message = "work 'RFC 9457' source 'RFC 9457' must be an http or https URL" }
            @{ Case = 'a stated that isn''t a URL'; Field = 'stated'; Value = 'the LICENSE file'
                Message = "work 'RFC 9457' stated 'the LICENSE file' must be an http or https URL" }
            @{ Case = 'a match prefix that isn''t a folder URL'; Field = 'match'; Value = @('https://www.rfc-editor.org/rfc/rfc9457')
                Message = "work 'RFC 9457' match 'https://www.rfc-editor.org/rfc/rfc9457' must be an http or https URL ending in '/'" }
            @{ Case = 'a | in its author'; Field = 'author'; Value = 'IETF | IRTF'
                Message = "work 'RFC 9457' author has a '|', which would break the notices table" }
            @{ Case = 'a | in its title'; Field = 'title'; Value = 'RFC | 9457'
                Message = "work 'RFC | 9457' title has a '|', which would break the notices table" }
            @{ Case = 'a | in its copyright'; Field = 'copyright'; Value = 'IETF | IRTF'
                Message = "work 'RFC 9457' copyright has a '|', which would break the notices table" }
        ) {
            $work = New-Work
            $work[$Field] = $Value

            (Get-CheckOutput -Works @($work) -Licenses @((New-License), (New-License -Id 'Other'))).Lines | Should -Contain $Message
        }

        It 'reports two works with one title' {
            $other = New-Work
            $other['match'] = @('https://www.rfc-editor.org/rfc/')

            $lines = (Get-CheckOutput -Works @((New-Work), $other) -Licenses @(New-License)).Lines

            $lines | Should -Contain "work 'RFC 9457' has the same title as another; give each its own"
            # Each work keeps its own quotes, whatever its title: the longer prefix takes the quote, so the other has none.
            @($lines | Where-Object { $_ -eq "work 'RFC 9457' matches no quoted page; remove it" }).Count | Should -Be 1
        }

        It 'reports a license whose url isn''t an http or https URL' {
            $license = New-License
            $license['url'] = 'creativecommons.org'

            (Get-CheckOutput -Works @(New-Work) -Licenses @($license)).Lines |
                Should -Contain "license 'CC-BY-4.0' url 'creativecommons.org' must be an http or https URL"
        }

        It 'stops with the reason when <Key> isn''t a list' -ForEach @(@{ Key = 'works' }, @{ Key = 'licenses' }) {
            $path = Join-Path $TestDrive "authorities-$(New-Guid).yml"
            Set-Content -Path $path -Value "sources: []`n${Key}: some text`n"

