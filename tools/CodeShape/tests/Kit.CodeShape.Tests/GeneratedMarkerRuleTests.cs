namespace Kit.CodeShape.Tests;

// The compiler treats a file marked as generated as nullable-disabled and its analyzers skip it, as these checks and the
// coverage gate do; so only EF Core's migrations, which it generates, may carry a marker (STY-005).
public sealed class GeneratedMarkerRuleTests
{
    private const string Message =
        "The file is marked as generated code, which the compiler's nullable analysis, its analyzers and these checks skip; only EF Core migrations, in a Migrations folder, may be (STY-005).";

    [Theory]
    [InlineData("Widget.g.cs", "")]
    [InlineData("Widget.Designer.cs", "")]
    [InlineData("Widget.cs", "// <auto-generated/>\n")]
    public void AMarkedFileOutsideMigrationsIsReportedAtItsFirstLine(string name, string header) =>
        GeneratedMarkerRule.Check(Marked(Path.Join("src", "App", name), header))
            .Should().ContainSingle().Which.Should().BeEquivalentTo(new { Line = 1, Column = 1, Message });

    [Theory]
    [InlineData("20261116000000_Initial.cs", "// <auto-generated />\n")]
    [InlineData("20261116000000_Initial.Designer.cs", "// <auto-generated />\n")]
    [InlineData("AppDbContextModelSnapshot.cs", "// <auto-generated />\n")]
    public void AnEfCoreMigrationMayBeMarked(string name, string header) =>
        GeneratedMarkerRule.Check(Marked(Path.Join("src", "App", "Migrations", name), header)).Should().BeEmpty();

    [Fact]
    public void AnUnmarkedFileHasNoFinding() =>
        GeneratedMarkerRule.Check(new SourceFile(Path.Join("src", "App", "Widget.cs"), "class Widget { }")).Should().BeEmpty();

    private static SourceFile Marked(string path, string header)
    {
        SourceFile file = new(path, header + "class Widget { }");
        return file with { Generated = GeneratedCode.Is(file) };
    }
}
