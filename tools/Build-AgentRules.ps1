#Requires -Version 7.0
<#
.SYNOPSIS
    Generates the agents' path-scoped rule files from docs/standards (checkpoint §2).

.DESCRIPTION
    For each docs/standards/*.md, writes its accepted rules as one-line statements to:
      .claude/rules/<topic>.md                         Claude Code, always loaded (rules with paths **)
      .claude/rules/<topic>-<rule-id>.md               Claude Code, loaded by paths: (one per distinct path set)
      .github/instructions/<topic>[-<rule-id>].instructions.md   Copilot, the same split with applyTo:
    Also writes .github/copilot-instructions.md as a copy of AGENTS.md, because Visual Studio reads that
    file but doesn't document reading AGENTS.md. Proposed and retired rules aren't in force, so they're
    left out. Generated files carry a marker; generated files no standard produces any more are removed.

    -Check writes nothing and exits 1 when any generated file is missing, hand-edited or stale (S3).

.EXAMPLE
    ./tools/Build-AgentRules.ps1
    Regenerate after editing a standard or AGENTS.md, then commit the result.

.EXAMPLE
    ./tools/Build-AgentRules.ps1 -Check
    Fails if the committed files don't match the sources (CI runs this from build step 4).
#>
[CmdletBinding()]
param(
    [string] $RepoRoot,
    [switch] $Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Import-Module, not '#Requires -Modules', which breaks exit codes under -File (see tools/Test-RuleSources.ps1).
Import-Module -Name 'powershell-yaml' -MinimumVersion '0.4.12'
Import-Module -Name (Join-Path $PSScriptRoot 'KitFrontMatter.psm1') -Force

$script:GeneratedMarker = '<!-- Generated by tools/Build-AgentRules.ps1 from {0}. Do not edit; edit the source and run ./tools/Build-AgentRules.ps1. -->'

function ConvertTo-RuleBody {
    param(
        [Parameter(Mandatory)] [string] $SourceName,
        [Parameter(Mandatory)] [string] $Title,
        [Parameter(Mandatory)] [object[]] $Rules
    )
    $lines = @(($script:GeneratedMarker -f "docs/standards/$SourceName"), '', "# $Title", '')
    foreach ($rule in $Rules) {
        $lines += "- $($rule['id']): $($rule['statement'])"
    }
    ($lines -join "`n") + "`n"
}

# Builds every generated rule file in memory: for each standard, its accepted rules split into always-on
# rules (paths include **) and path-scoped rules, written once for Claude Code (.claude/rules, paths:)
# and once for Copilot (.github/instructions, applyTo:). Proposed and retired rules aren't in force.
function Get-AgentRuleFile {
    param([Parameter(Mandatory)] [string] $StandardsPath)

    foreach ($file in Get-ChildItem -Path $StandardsPath -Filter '*.md' -File | Sort-Object Name) {
        $frontMatter = Read-FrontMatter -Path $file.FullName
        if ($null -eq $frontMatter -or -not $frontMatter.Contains('rules')) {
            continue
        }
        $topic = $file.BaseName
        $title = (Read-MarkdownBody -Path $file.FullName) -split "`n" | Where-Object { $_ -match '^# ' } | Select-Object -First 1
        $title = if ($title) { $title -replace '^# ', '' } else { $topic }

        $accepted = @($frontMatter['rules'] | Where-Object { $_['status'] -eq 'accepted' })
        $always = @($accepted | Where-Object { @($_['paths']) -contains '**' -or -not $_.Contains('paths') })
        $scoped = @($accepted | Where-Object { $_ -notin $always })

        if ($always) {
            $body = ConvertTo-RuleBody -SourceName $file.Name -Title $title -Rules $always
            [pscustomobject]@{ Path = ".claude/rules/$topic.md"; Content = $body }
            [pscustomobject]@{ Path = ".github/instructions/$topic.instructions.md"; Content = "---`napplyTo: '**'`n---`n$body" }
        }
        # One file per distinct set of paths, so each rule loads only where it applies. A group is named
        # after its first rule, which keeps file names stable when other rules change.
        $groups = [ordered]@{}
        foreach ($rule in $scoped) {
            $key = (@($rule['paths']) | Sort-Object -Unique) -join "`n"
            if (-not $groups.Contains($key)) { $groups[$key] = [System.Collections.Generic.List[object]]::new() }
            $groups[$key].Add($rule)
        }
        foreach ($group in $groups.Values) {
            $name = "$topic-$("$($group[0]['id'])".ToLowerInvariant())"
            $paths = @($group[0]['paths'] | ForEach-Object { "$_" -replace "'", "''" })
            $body = ConvertTo-RuleBody -SourceName $file.Name -Title $title -Rules $group
            $pathLines = ($paths | ForEach-Object { "  - '$_'" }) -join "`n"
            [pscustomobject]@{ Path = ".claude/rules/$name.md"; Content = "---`npaths:`n$pathLines`n---`n$body" }
            [pscustomobject]@{ Path = ".github/instructions/$name.instructions.md"; Content = "---`napplyTo: '$($paths -join ',')'`n---`n$body" }
        }
    }
}

# Visual Studio reads .github/copilot-instructions.md but doesn't document reading AGENTS.md, so the
# repository instructions are a generated copy of AGENTS.md: one source, no drift.
function Get-CopilotInstructionsFile {
    param([Parameter(Mandatory)] [string] $AgentsPath)

    $agents = (Get-Content -Path $AgentsPath -Raw) -replace "`r`n", "`n"
    $content = ($script:GeneratedMarker -f 'AGENTS.md') + "`n`n" + $agents.TrimEnd("`n") + "`n"
    [pscustomobject]@{ Path = '.github/copilot-instructions.md'; Content = $content }
}

# Writes every generated file and deletes generated files no standard produces any more. With -Check it
# writes nothing and returns 1 if any file is missing, different or stale (S3: hand-edited copies are
# flagged). Line endings don't count: git may check files out with CRLF.
function Invoke-AgentRuleBuild {
    param(
        [Parameter(Mandatory)] [string] $RepoRoot,
        [switch] $Check
    )

    # .NET path APIs resolve a relative path against the process directory, which Set-Location doesn't
    # change; resolve it through PowerShell first, or every generated file looks stale and gets deleted.
    $RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).ProviderPath

    $expected = @(Get-AgentRuleFile -StandardsPath (Join-Path $RepoRoot 'docs' 'standards'))
    $expected += Get-CopilotInstructionsFile -AgentsPath (Join-Path $RepoRoot 'AGENTS.md')
    $expectedPaths = @($expected | ForEach-Object Path)

    # Each entry: what -Check reports, and what a build reports after fixing it.
    $drift = [System.Collections.Generic.List[pscustomobject]]::new()
    foreach ($file in $expected) {
        $target = Join-Path $RepoRoot $file.Path
        $current = if (Test-Path -Path $target) { (Get-Content -Path $target -Raw) -replace "`r`n", "`n" } else { $null }
        if ($current -cne $file.Content) {
            $drift.Add([pscustomobject]@{ Check = "out of date: $($file.Path)"; Build = "updated: $($file.Path)" })
            if (-not $Check) {
                New-Item -ItemType Directory -Path (Split-Path -Path $target -Parent) -Force | Out-Null
                Set-Content -Path $target -Value $file.Content -NoNewline
            }
        }
    }

    # Only files carrying the generated marker are the generator's to remove; hand-written ones stay.
    $markerStart = '<!-- Generated by tools/Build-AgentRules.ps1 from '
    foreach ($folder in '.claude/rules', '.github/instructions') {
        $directory = Join-Path $RepoRoot $folder
        if (-not (Test-Path -Path $directory)) { continue }
        foreach ($existing in Get-ChildItem -Path $directory -Filter '*.md' -File -Recurse) {
            $relative = [System.IO.Path]::GetRelativePath($RepoRoot, $existing.FullName) -replace '\\', '/'
            if ($relative -in $expectedPaths) { continue }
            if ((Get-Content -Path $existing.FullName -Raw) -match [regex]::Escape($markerStart)) {
                $drift.Add([pscustomobject]@{ Check = "stale: $relative"; Build = "removed: $relative" })
                if (-not $Check) {
                    Remove-Item -Path $existing.FullName
                }
            }
        }
    }

    if ($Check) {
        foreach ($entry in $drift) {
            Write-Host "  $($entry.Check)" -ForegroundColor Red
        }
        if ($drift.Count -gt 0) {
            Write-Host "`n$($drift.Count) generated file(s) out of date. Run ./tools/Build-AgentRules.ps1 and commit the result." -ForegroundColor Red
            return 1
        }
        Write-Host "$($expected.Count) generated files, all current." -ForegroundColor Green
        return 0
    }

    foreach ($entry in $drift) {
        Write-Host "  $($entry.Build)" -ForegroundColor Cyan
    }
    Write-Host "$($expected.Count) generated files written ($($drift.Count) changed)." -ForegroundColor Green
    0
}

# Run when invoked as a script; stay quiet when dot-sourced (the tests do that).
if ($MyInvocation.InvocationName -ne '.') {
    if (-not $RepoRoot) { $RepoRoot = Split-Path -Path $PSScriptRoot -Parent }
    exit (Invoke-AgentRuleBuild -RepoRoot $RepoRoot -Check:$Check)
}
